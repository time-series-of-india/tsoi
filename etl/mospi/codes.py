import re


def norm(s):
    """Fold a display name to a lookup key: case, dashes, quotes, and '&'."""
    s = (s or "").strip().lower().replace("\u2013", "-").replace("\u2019", "'")
    s = re.sub(r"\s*&\s*", " and ", s)
    return re.sub(r"\s+", " ", s)


